// fileRepo is a repository directory by name and size alone, for the upload and mirror logic.
func fileRepo(t *testing.T, sizes map[string]int) (string, []repoFile, []*Package) {
	t.Helper()
	dir := t.TempDir()
	var pkgs []*Package
	for n, s := range sizes {
		if err := os.WriteFile(filepath.Join(dir, n), bytes.Repeat([]byte{1}, s), 0o644); err != nil {
			t.Fatal(err)
		}
		if strings.HasSuffix(n, pkgSuffix) {
			pkgs = append(pkgs, &Package{File: n, Size: int64(s)})
		}
	}
	files, err := repoFiles(dir)
	if err != nil {
		t.Fatal(err)
	}
	return dir, files, pkgs
}

var smallRepo = map[string]int{
	"linux-runink-7.2.7.zen1-1-x86_64.pkg.tar.zst": 3000, "linux-runink-7.2.7.zen1-1-x86_64.pkg.tar.zst.sig": 10,
	"runink-tayga-0.9.2-1-x86_64.pkg.tar.zst": 500, "runink-tayga-0.9.2-1-x86_64.pkg.tar.zst.sig": 10,
	"runink.db": 50, "runink.db.sig": 10, "runink.files": 60, "runink.files.sig": 10,
	"SHA256SUMS": 20, "SHA256SUMS.sig": 10,
}

func TestWritePagesSplitsBySize(t *testing.T) {
	dir, files, pkgs := fileRepo(t, smallRepo)
	out := filepath.Join(t.TempDir(), "static/river/repo/x86_64")
	var log bytes.Buffer
	if err := writePages(dir, out, files, pkgs, 1000, &log); err != nil {
		t.Fatal(err)
	}
	got, _ := os.ReadDir(out)
	var names []string
	for _, e := range got {
		names = append(names, e.Name())
		if !e.Type().IsRegular() {
			t.Errorf("%s is not a regular file", e.Name())
		}
	}
	want := []string{"SHA256SUMS", "SHA256SUMS.sig", "runink-tayga-0.9.2-1-x86_64.pkg.tar.zst", "runink-tayga-0.9.2-1-x86_64.pkg.tar.zst.sig",
		"runink.db", "runink.db.sig", "runink.files", "runink.files.sig"}
	if !slices.Equal(names, want) {
		t.Fatalf("mirror holds %v, want %v", names, want)
	}
	if !strings.Contains(log.String(), "NOT mirrored, over the Pages limit (GitHub release only): linux-runink") {
		t.Fatalf("the omission must be reported:\n%s", log.String())
	}

	// A second publish removes what the repository no longer has and keeps nothing stale.
	stale := filepath.Join(out, "runink-tayga-0.9.1-1-x86_64.pkg.tar.zst")
	if err := os.WriteFile(stale, nil, 0o644); err != nil {
		t.Fatal(err)
	}
	if err := writePages(dir, out, files, pkgs, 1000, io.Discard); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(stale); err == nil {
		t.Fatal("a superseded package stayed on the mirror")
	}

	// Anything that is not a repository file means --pages-out points at the wrong directory.
	if err := os.WriteFile(filepath.Join(out, "index.html"), nil, 0o644); err != nil {
		t.Fatal(err)
	}
	if err := writePages(dir, out, files, pkgs, 1000, io.Discard); err == nil || !strings.Contains(err.Error(), "index.html") {
		t.Fatalf("got %v", err)
	}
}

