type ghCall []string

func fakeGH(t *testing.T, view string, viewErr error) *[]ghCall {
	t.Helper()
	var calls []ghCall
	old := gh
	t.Cleanup(func() { gh = old })
	gh = func(_ context.Context, args ...string) ([]byte, error) {
		calls = append(calls, args)
		if args[1] == "view" {
			return []byte(view), viewErr
		}
		return nil, nil
	}
	return &calls
}

func TestPublishGitHubCreatesPrerelease(t *testing.T) {
	dir, files, _ := fileRepo(t, smallRepo)
	calls := fakeGH(t, "", fmt.Errorf("stage 1 (gh release view): exit status 1: release not found"))
	o := PublishOptions{GitHubRepo: GitHubRepo, Tag: ReleaseTag, Prune: true}
	if err := publishGitHub(context.Background(), o, dir, files, io.Discard); err != nil {
		t.Fatal(err)
	}
	create := strings.Join((*calls)[1], " ")
	for _, want := range []string{"release create " + ReleaseTag, "--prerelease", "--latest=false", "-R " + GitHubRepo} {
		if !strings.Contains(create, want) {
			t.Errorf("create %q lacks %q", create, want)
		}
	}
	// Packages go up first, the database last.
	up1, up2 := strings.Join((*calls)[2], " "), strings.Join((*calls)[3], " ")
	if !strings.Contains(up1, "upload "+ReleaseTag+" --clobber") || strings.Contains(up1, "runink.db") || !strings.Contains(up1, "runink-tayga") {
		t.Errorf("first upload must be the packages only: %s", up1)
	}
	if !strings.Contains(up2, "runink.db") || strings.Contains(up2, pkgSuffix+" ") {
		t.Errorf("second upload must be the database: %s", up2)
	}
	if len(*calls) != 4 {
		t.Errorf("a new release has nothing to prune; calls: %v", *calls)
	}
}

func TestPublishGitHubPrunesAfterUpload(t *testing.T) {
	dir, files, _ := fileRepo(t, smallRepo)
	view := `{"isPrerelease":true,"isDraft":false,"assets":[{"name":"runink.db"},{"name":"runink-tayga-0.9.1-1-x86_64.pkg.tar.zst"}]}`
	calls := fakeGH(t, view, nil)
	if err := publishGitHub(context.Background(), PublishOptions{GitHubRepo: GitHubRepo, Tag: ReleaseTag, Prune: true}, dir, files, io.Discard); err != nil {
		t.Fatal(err)
	}
	last := strings.Join((*calls)[len(*calls)-1], " ")
	if !strings.Contains(last, "delete-asset "+ReleaseTag+" runink-tayga-0.9.1-1-x86_64.pkg.tar.zst --yes") {
		t.Fatalf("the superseded asset is deleted last: %v", *calls)
	}
}

