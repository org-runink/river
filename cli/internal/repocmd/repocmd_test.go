func TestImageTrustsReleaseKey(t *testing.T) {
	r := root(t)
	fpr, keyFile, err := resolveKey(r, "", "")
	if err != nil {
		t.Fatal(err)
	}
	shipped, err := os.ReadFile(keyFile)
	if err != nil {
		t.Fatalf("the release public key must be in the tree (base/keys/owner/<fpr>.asc): %v", err)
	}
	kr := filepath.Join(r, "iso-profiles/river/root-overlay/usr/share/pacman/keyrings")
	img, err := os.ReadFile(filepath.Join(kr, "runink.gpg"))
	if err != nil || !bytes.Equal(img, shipped) {
		t.Fatalf("the image's pacman keyring runink.gpg must be byte-identical to %s (err %v)", keyFile, err)
	}
	if _, err := keyringFromArmor(keyFile); err != nil {
		t.Fatal(err)
	}
	trusted, err := os.ReadFile(filepath.Join(kr, "runink-trusted"))
	if err != nil || !regexp.MustCompile(`(?m)^`+fpr+`:4:$`).Match(trusted) {
		t.Fatalf("runink-trusted must trust %s (err %v):\n%s", fpr, err, trusted)
	}
	for _, f := range []string{"KEYS", "install.sh"} {
		b, err := os.ReadFile(filepath.Join(r, f))
		if err != nil || !bytes.Contains(b, []byte(fpr)) {
			t.Errorf("%s does not carry the fingerprint %s", f, fpr)
		}
	}
	ml, err := os.ReadFile(filepath.Join(r, "iso-profiles/river/root-overlay/etc/pacman.d/mirrorlist-runink"))
	if err != nil {
		t.Fatal(err)
	}
	var servers []string
	for _, l := range strings.Split(string(ml), "\n") {
		if strings.HasPrefix(l, "Server = ") {
			servers = append(servers, strings.TrimPrefix(l, "Server = "))
		}
	}
	want := []string{"https://github.com/org-runink/river/releases/download/" + ReleaseTag, "https://runink.org/river/repo/x86_64"}
	if !slices.Equal(servers, want) {
		t.Fatalf("mirrorlist-runink servers %v, want %v", servers, want)
	}
}

