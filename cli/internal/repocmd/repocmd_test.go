func TestCheckPublic(t *testing.T) {
	with := func(f fakePkg, extra map[string]string) fakePkg {
		m := map[string]string{}
		for k, v := range f.files {
			m[k] = v
		}
		for k, v := range extra {
			if v == "<delete>" {
				delete(m, k)
				continue
			}
			m[k] = v
		}
		f.files = m
		return f
	}
	cases := []struct {
		name string
		pkg  fakePkg
		dir  string
		file string // override the file name
		want string // "" = public; else a fragment of the refusal
	}{
		{"base runink-core", baseCore, "", "", ""},
		{"base runink-runtime", baseRuntime, "", "", ""},
		{"runtime with the models manifest", with(baseRuntime, map[string]string{"usr/local/share/runink/models.manifest": "x"}), "", "", ""},
		{"a River package", tayga, "", "", ""},
		{"not on the allow-list", fakePkg{name: "acme-console", ver: "1-1", arch: "x86_64", files: map[string]string{"usr/bin/acme": "x"}}, "", "", "not on the public allow-list"},
		{"core with a deploy", with(baseCore, map[string]string{"usr/local/share/runink/core/deploy": "#!/bin/sh"}), "", "", "downstream payload file"},
		{"core with firstboot hooks", with(baseCore, map[string]string{"usr/local/lib/runink/firstboot.d/50-x": "x"}), "", "", "downstream payload file"},
		{"core without the marker", with(baseCore, map[string]string{coreMarker: "<delete>"}), "", "", "has no " + coreMarker},
		{"downstream core (full tree, no marker)", with(baseCore, map[string]string{coreMarker: "<delete>", "usr/local/share/runink/core/deploy": "x", "usr/local/share/runink/core/bin/core": "x"}), "", "", "2 downstream payload file(s)"},
		{"runtime with host binaries", with(baseRuntime, map[string]string{"usr/local/bin/objectd": "x"}), "", "", "downstream payload file"},
		{"runtime with an OCI image", with(baseRuntime, map[string]string{"usr/local/share/runink/images/app.tar": "x"}), "", "", "downstream payload file"},
		{"other package under a payload path", with(tayga, map[string]string{"usr/local/share/runink/core/deploy": "x"}), "", "", "downstream payload file"},
		{"private directory", tayga, "/build/state/localrepo-server-private", "", "private build directory"},
		{"server profile directory", tayga, "/build/state/localrepo-runink-server", "", "private build directory"},
		{"PRIVATE in capitals", tayga, "/x/PRIVATE/y", "", "private build directory"},
		{"file name not its .PKGINFO", tayga, "", "runink-tayga-9.9-1-x86_64" + pkgSuffix, "does not match its .PKGINFO"},
		{"a character GitHub rewrites", fakePkg{name: "runink-tayga", ver: "0.9.2+r1-1", arch: "x86_64"}, "", "", "GitHub would rewrite"},
		{"foreign arch", fakePkg{name: "runink-tayga", ver: "1-1", arch: "aarch64"}, "", "", "not x86_64"},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			dir := c.dir
			if dir == "" {
				dir = "/build/localrepo-river"
			}
			p := c.pkg.read(t, dir)
			if c.file != "" {
				p.File = c.file
			}
			why := strings.Join(CheckPublic(p), "\n")
			if c.want == "" && why != "" {
				t.Fatalf("refused a public package: %s", why)
			}
			if c.want != "" && !strings.Contains(why, c.want) {
				t.Fatalf("want a refusal containing %q, got %q", c.want, why)
			}
		})
	}
}

// The allow-list is exactly what River's own PKGBUILDs build: a new PKGBUILD must be added to
// it on purpose, and a removed one taken off.
func TestPublicPackagesMatchPKGBUILDs(t *testing.T) {
	r := root(t)
	builds, _ := filepath.Glob(filepath.Join(r, "build/pkgbuilds/*/PKGBUILD"))
	if len(builds) == 0 {
		t.Fatal("no PKGBUILDs")
	}
	baseRE := regexp.MustCompile(`(?m)^pkgbase=(\S+)`)
	nameRE := regexp.MustCompile(`(?m)^pkgname=(\([^)]*\)|\S+)`)
	got := map[string]string{}
	for _, b := range builds {
		src, err := os.ReadFile(b)
		if err != nil {
			t.Fatal(err)
		}
		base := ""
		if m := baseRE.FindSubmatch(src); m != nil {
			base = strings.Trim(string(m[1]), `"'`)
		}
		m := nameRE.FindSubmatch(src)
		if m == nil {
			t.Fatalf("%s: no pkgname", b)
		}
		for _, n := range strings.Fields(strings.Trim(string(m[1]), "()")) {
			n = strings.ReplaceAll(strings.Trim(n, `"'`), "$pkgbase", base)
			got[n] = filepath.ToSlash(strings.TrimPrefix(filepath.Dir(b), r+"/"))
		}
	}
	for n, d := range got {
		if PublicPackages[n] != d {
			t.Errorf("%s (built by %s) is not in PublicPackages with that directory", n, d)
		}
	}
	for n := range PublicPackages {
		if _, ok := got[n]; !ok {
			t.Errorf("PublicPackages lists %s, which no PKGBUILD builds", n)
		}
	}
}

