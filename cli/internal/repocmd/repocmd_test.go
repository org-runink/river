// tarBytes is the uncompressed package archive makepkg would write.
func (f fakePkg) tarBytes(t *testing.T) []byte {
	t.Helper()
	var b bytes.Buffer
	tw := tar.NewWriter(&b)
	add := func(name string, typ byte, body string) {
		h := &tar.Header{Name: name, Typeflag: typ, Mode: 0o644, Size: int64(len(body))}
		if typ == tar.TypeDir {
			h.Mode, h.Size = 0o755, 0
		}
		if err := tw.WriteHeader(h); err != nil {
			t.Fatal(err)
		}
		if typ != tar.TypeDir {
			if _, err := io.WriteString(tw, body); err != nil {
				t.Fatal(err)
			}
		}
	}
	add(".BUILDINFO", tar.TypeReg, "format = 2\n")
	add(".MTREE", tar.TypeReg, "")
	add(".PKGINFO", tar.TypeReg, fmt.Sprintf("# Generated by makepkg\npkgname = %s\npkgbase = %s\npkgver = %s\narch = %s\nsize = 1\n", f.name, f.name, f.ver, f.arch))
	for _, d := range f.dirs {
		add(d+"/", tar.TypeDir, "")
	}
	names := make([]string, 0, len(f.files))
	for n := range f.files {
		names = append(names, n)
	}
	slices.Sort(names)
	for _, n := range names {
		add(n, tar.TypeReg, f.files[n])
	}
	if err := tw.Close(); err != nil {
		t.Fatal(err)
	}
	return b.Bytes()
}

// read parses the fixture the way OpenPackage does, without zstd.
func (f fakePkg) read(t *testing.T, dir string) *Package {
	t.Helper()
	p, err := readPackage(bytes.NewReader(f.tarBytes(t)))
	if err != nil {
		t.Fatal(err)
	}
	p.File = f.fileName()
	p.Path = filepath.Join(dir, p.File)
	return p
}

func needTools(t *testing.T, names ...string) {
	t.Helper()
	for _, n := range names {
		if _, err := exec.LookPath(n); err != nil {
			t.Skipf("%s not installed: this test builds or reads real .pkg.tar.zst/signatures (the pure-Go tests cover the rules)", n)
		}
	}
}

// writeZst writes b to path compressed with the zstd tool.
func writeZst(t *testing.T, path string, b []byte) {
	t.Helper()
	cmd := exec.Command("zstd", "-q", "-f", "-o", path)
	cmd.Stdin = bytes.NewReader(b)
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("zstd: %v: %s", err, out)
	}
}

func (f fakePkg) write(t *testing.T, dir string) string {
	t.Helper()
	p := filepath.Join(dir, f.fileName())
	writeZst(t, p, f.tarBytes(t))
	return p
}

