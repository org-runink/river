// testKey makes a throwaway signing key in a private GNUPGHOME (never the release key) and
// returns a signer and the armored public key file.
func testKey(t *testing.T, uid string) (fpr, asc string, sign func(file string)) {
	t.Helper()
	home, err := os.MkdirTemp("", "rrk")
	if err != nil {
		t.Fatal(err)
	}
	if err := os.Chmod(home, 0o700); err != nil {
		t.Fatal(err)
	}
	env := append(os.Environ(), "GNUPGHOME="+home)
	t.Cleanup(func() {
		c := exec.Command("gpgconf", "--kill", "all")
		c.Env = env
		_ = c.Run()
		os.RemoveAll(home)
	})
	run := func(args ...string) []byte {
		c := exec.Command("gpg", append([]string{"--batch", "--yes", "--quiet"}, args...)...)
		c.Env = env
		out, err := c.Output()
		if err != nil {
			t.Fatalf("gpg %v: %v", args, err)
		}
		return out
	}
	run("--passphrase", "", "--quick-gen-key", uid, "ed25519", "sign", "never")
	for _, l := range strings.Split(string(run("--with-colons", "--list-keys")), "\n") {
		if f := strings.Split(l, ":"); f[0] == "fpr" {
			fpr = f[9]
			break
		}
	}
	asc = filepath.Join(home, "pub.asc")
	if err := os.WriteFile(asc, run("--armor", "--export", fpr), 0o644); err != nil {
		t.Fatal(err)
	}
	return fpr, asc, func(file string) { run("--local-user", fpr, "--detach-sign", "--output", file+".sig", file) }
}

// signedRepo builds a small repository (packages, a database repo-add would write, SHA256SUMS)
// and signs every file the way base/river-sign does.
func signedRepo(t *testing.T, sign func(string)) string {
	t.Helper()
	dir := t.TempDir()
	pkgs := []fakePkg{baseCore, tayga}
	var db bytes.Buffer
	tw := tar.NewWriter(&db)
	for _, p := range pkgs {
		p.write(t, dir)
		desc := fmt.Sprintf("%%FILENAME%%\n%s\n\n%%NAME%%\n%s\n", p.fileName(), p.name)
		_ = tw.WriteHeader(&tar.Header{Name: p.name + "-" + p.ver + "/desc", Mode: 0o644, Size: int64(len(desc)), Typeflag: tar.TypeReg})
		_, _ = io.WriteString(tw, desc)
	}
	_ = tw.Close()
	writeZst(t, filepath.Join(dir, dbFile), db.Bytes())
	writeZst(t, filepath.Join(dir, filesFile), db.Bytes())
	for _, l := range []string{"db", "files"} {
		if err := os.Symlink(RepoName+"."+l+".tar.zst", filepath.Join(dir, RepoName+"."+l)); err != nil {
			t.Fatal(err)
		}
	}
	names := []string{dbFile, filesFile}
	for _, p := range pkgs {
		names = append(names, p.fileName())
	}
	if err := writeSums(dir, names); err != nil {
		t.Fatal(err)
	}
	for _, n := range append(names, "SHA256SUMS") {
		sign(filepath.Join(dir, n))
	}
	for _, l := range []string{"db", "files"} {
		if err := os.Symlink(RepoName+"."+l+".tar.zst.sig", filepath.Join(dir, RepoName+"."+l+".sig")); err != nil {
			t.Fatal(err)
		}
	}
	return dir
}

func TestVerifyEndToEnd(t *testing.T) {
	needTools(t, "gpg", "gpgv", "gpgconf", "zstd")
	fpr, asc, sign := testKey(t, "River repo test <test@example.invalid>")
	ctx := context.Background()

	dir := signedRepo(t, sign)
	if err := Verify(ctx, dir, fpr, asc, io.Discard); err != nil {
		t.Fatalf("a correctly signed repository failed: %v", err)
	}

	mustFail := func(name, want string, mutate func(dir string)) {
		t.Run(name, func(t *testing.T) {
			d := signedRepo(t, sign)
			mutate(d)
			err := Verify(ctx, d, fpr, asc, io.Discard)
			if err == nil || !strings.Contains(err.Error(), want) {
				t.Fatalf("want a failure containing %q, got %v", want, err)
			}
		})
	}
	mustFail("a package without its signature", "no signature", func(d string) {
		os.Remove(filepath.Join(d, tayga.fileName()+".sig"))
	})
	mustFail("the database without its signature", "runink.db: no signature", func(d string) {
		os.Remove(filepath.Join(d, "runink.db.sig"))
	})
	mustFail("a package changed after signing", "does not verify", func(d string) {
		p := filepath.Join(d, tayga.fileName())
		b, _ := os.ReadFile(p)
		os.WriteFile(p, append(b, 0), 0o644)
	})
	mustFail("a stray file", "not a repository file", func(d string) {
		os.WriteFile(filepath.Join(d, "notes.txt"), nil, 0o644)
	})
	mustFail("a package the database does not name", "not in runink.db", func(d string) {
		p := fakePkg{name: "runink-zfs", ver: "2.4.4-3", arch: "x86_64"}
		f := p.write(t, d)
		sign(f)
	})
	mustFail("the wrong key", "does not verify", func(d string) {
		_, _, other := testKey(t, "Someone else <else@example.invalid>")
		other(filepath.Join(d, tayga.fileName()))
	})
	// Right key file, wrong expected fingerprint: fails closed.
	if err := Verify(ctx, dir, "95C0A7B97D547413E42660DDB06FE75626F15BF3", asc, io.Discard); err == nil {
		t.Fatal("verified against a fingerprint that did not sign")
	}
}

