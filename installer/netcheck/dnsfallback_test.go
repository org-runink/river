func writeRoute(t *testing.T, root string, withDefault bool) {
	t.Helper()
	os.MkdirAll(filepath.Join(root, "proc/net"), 0o755)
	route := "Iface\tDestination\tGateway\tFlags\tRefCnt\tUse\tMetric\tMask\n"
	if withDefault {
		route += "eth0\t00000000\t0100000A\t0003\t0\t0\t100\t00000000\n"
	}
	route += "eth0\t0000000A\t00000000\t0001\t0\t0\t100\t00FFFFFF\n"
	os.WriteFile(filepath.Join(root, "proc/net/route"), []byte(route), 0o644)
}

func TestDNSComposeWritesAndIsIdempotent(t *testing.T) {
	dir := t.TempDir()
	writeRoute(t, dir, true)
	src, out, conf := filepath.Join(dir, "nm.conf"), filepath.Join(dir, "resolv.conf"), filepath.Join(dir, "fb.conf")
	os.WriteFile(src, []byte(nmDual), 0o644)
	os.WriteFile(conf, []byte("FALLBACK_DNS=203.0.113.9\nDNS_OPTIONS=timeout:2\n"), 0o644)
	var e bytes.Buffer
	if rc := dnsCompose(src, out, conf, dir, false, &e, &e); rc != 0 {
		t.Fatalf("rc %d: %s", rc, e.String())
	}
	b, _ := os.ReadFile(out)
	if ns := nameservers(string(b)); len(ns) < 2 || ns[1] != "203.0.113.9" {
		t.Fatalf("fallback not second: %v", ns)
	}
	fi, _ := os.Stat(out)
	if fi.Mode().Perm() != 0o644 {
		t.Errorf("mode %v, want 0644", fi.Mode().Perm())
	}
	if rc := dnsCompose(src, out, conf, dir, false, &e, &e); rc != 0 {
		t.Fatalf("second run rc %d", rc)
	}
}

func TestDNSComposeLeavesForeignSymlinkAndMissingSource(t *testing.T) {
	dir := t.TempDir()
	writeRoute(t, dir, true)
	src, out, conf := filepath.Join(dir, "nm.conf"), filepath.Join(dir, "resolv.conf"), filepath.Join(dir, "fb.conf")
	other := filepath.Join(dir, "mine.conf")
	os.WriteFile(other, []byte("nameserver 192.0.2.7\n"), 0o644)
	os.Symlink(other, out)
	os.WriteFile(conf, []byte("FALLBACK_DNS=203.0.113.9\n"), 0o644)
	var e bytes.Buffer
	if rc := dnsCompose(src, out, conf, dir, false, &e, &e); rc != 0 { // no NetworkManager file
		t.Fatalf("missing source rc %d", rc)
	}
	os.WriteFile(src, []byte(nmDual), 0o644)
	if rc := dnsCompose(src, out, conf, dir, false, &e, &e); rc != 0 {
		t.Fatalf("rc %d", rc)
	}
	if b, _ := os.ReadFile(other); string(b) != "nameserver 192.0.2.7\n" {
		t.Fatalf("a resolv.conf link to the operator's own file was rewritten: %q", b)
	}
}

