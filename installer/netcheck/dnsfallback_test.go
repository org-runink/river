// The package creates the dispatcher link; the overlay ships the NetworkManager priorities
// and gai.conf.
func TestOverlayShipsTheFailsafe(t *testing.T) {
	ovl := "../../iso-profiles/river/root-overlay/etc"
	pkg, err := os.ReadFile("../../build/pkgbuilds/runink-installer/PKGBUILD")
	if err != nil || !strings.Contains(string(pkg), `ln -sf /usr/local/bin/river-netcheck "$pkgdir/etc/NetworkManager/dispatcher.d/40-river-dns-fallback"`) {
		t.Errorf("runink-installer must link dispatcher.d/40-river-dns-fallback to river-netcheck: %v", err)
	}
	nm, err := os.ReadFile(filepath.Join(ovl, "NetworkManager/conf.d/12-river-dns-order.conf"))
	if err != nil || !strings.Contains(string(nm), "ipv4.dns-priority=50") || !strings.Contains(string(nm), "ipv6.dns-priority=100") {
		t.Errorf("12-river-dns-order.conf: %v", err)
	}
	gai, err := os.ReadFile(filepath.Join(ovl, "gai.conf"))
	if err != nil {
		t.Fatal(err)
	}
	ula := strings.Index(string(gai), "precedence fc00::/7")
	v4 := strings.Index(string(gai), "precedence ::ffff:0:0/96")
	any6 := strings.Index(string(gai), "precedence ::/0")
	if ula < 0 || v4 < 0 || any6 < 0 {
		t.Fatalf("gai.conf lacks the ULA, IPv4 or global IPv6 line:\n%s", gai)
	}
	if !strings.Contains(string(gai), "precedence fc00::/7       45") || !strings.Contains(string(gai), "precedence ::ffff:0:0/96  40") || !strings.Contains(string(gai), "precedence ::/0           35") {
		t.Errorf("gai.conf precedences must order ULA > IPv4 > global IPv6:\n%s", gai)
	}
}
