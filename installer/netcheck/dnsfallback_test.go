// A NetworkManager resolv.conf on a dual-stack LAN: the router first, then the provider's
// IPv6 resolvers (documentation addresses).
const nmDual = `# Generated by NetworkManager
search home.arpa
nameserver 192.0.2.1
nameserver 2001:db8::53
nameserver 2001:db8::54
# NOTE: the libc resolver may not support more than 3 nameservers.
options edns0 timeout:5
`

var fb = fallbackConf{servers: []string{"203.0.113.9", "203.0.113.10"}, options: []string{"timeout:2", "attempts:2"}}

func nameservers(s string) []string {
	var out []string
	for _, l := range strings.Split(s, "\n") {
		if f := strings.Fields(l); len(f) == 2 && f[0] == "nameserver" {
			out = append(out, f[1])
		}
	}
	return out
}

func TestComposeKeepsLANFirstThenFallbacksThenIPv6(t *testing.T) {
	got := composeResolv(nmDual, fb, true)
	want := []string{"192.0.2.1", "203.0.113.9", "203.0.113.10", "2001:db8::53", "2001:db8::54"}
	if ns := nameservers(got); strings.Join(ns, " ") != strings.Join(want, " ") {
		t.Fatalf("nameservers %v, want %v\n%s", ns, want, got)
	}
	if !strings.Contains(got, "search home.arpa\n") {
		t.Errorf("search domain lost:\n%s", got)
	}
	if !strings.Contains(got, "options edns0 timeout:2 attempts:2\n") {
		t.Errorf("options not merged (our timeout replaces NetworkManager's):\n%s", got)
	}
}

// An IPv6 LAN resolver that comes first stays first: it is the one that answers the local names.
func TestComposeIPv6FirstResolverStaysFirst(t *testing.T) {
	got := nameservers(composeResolv("nameserver 2001:db8:1::1\nnameserver 2001:db8::53\n", fb, true))
	want := []string{"2001:db8:1::1", "203.0.113.9", "203.0.113.10", "2001:db8::53"}
	if strings.Join(got, " ") != strings.Join(want, " ") {
		t.Fatalf("nameservers %v, want %v", got, want)
	}
}

// IPv6-only mode: no IPv4 path, so no IPv4 fallback is added.
func TestComposeNoIPv4PathAddsNoFallback(t *testing.T) {
	got := nameservers(composeResolv(nmDual, fb, false))
	want := []string{"192.0.2.1", "2001:db8::53", "2001:db8::54"}
	if strings.Join(got, " ") != strings.Join(want, " ") {
		t.Fatalf("nameservers %v, want %v", got, want)
	}
}

func TestComposeNoDuplicateWhenFallbackIsTheLANResolver(t *testing.T) {
	got := nameservers(composeResolv("nameserver 203.0.113.9\n", fb, true))
	if strings.Join(got, " ") != "203.0.113.9 203.0.113.10" {
		t.Fatalf("nameservers %v", got)
	}
}

func TestReadFallbackConf(t *testing.T) {
	dir := t.TempDir()
	p := filepath.Join(dir, "dns-fallback.conf")
	if c, err := readFallbackConf(p); err != nil || len(c.servers) != 0 {
		t.Fatalf("missing file must be an empty config, got %+v %v", c, err)
	}
	os.WriteFile(p, []byte("# x\nFALLBACK_DNS=\"203.0.113.9, 203.0.113.10\"\nDNS_OPTIONS='timeout:2 attempts:2'\n"), 0o644)
	c, err := readFallbackConf(p)
	if err != nil || strings.Join(c.servers, " ") != "203.0.113.9 203.0.113.10" || strings.Join(c.options, " ") != "timeout:2 attempts:2" {
		t.Fatalf("got %+v %v", c, err)
	}
	for _, bad := range []string{"FALLBACK_DNS=2001:db8::1\n", "FALLBACK_DNS=example.org\n", "DNS_OPTIONS=rm -rf\n", "OTHER=1\n", "novalue\n"} {
		os.WriteFile(p, []byte(bad), 0o644)
		if _, err := readFallbackConf(p); err == nil {
			t.Errorf("%q: want an error", bad)
		}
	}
}

